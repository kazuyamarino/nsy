#!/bin/bash
run_help() {
	printf "NAME :\n"
	printf " NSY Command Line Interface\n\n"
	printf "USAGE :\n"
	printf " * nsy [command] [command options] [arguments...]\n"
	printf " * nsy [command] [arguments...]\n\n"
	printf "VERSION :\n"
	printf " %s\n\n" "$NSY_CLI_VERSION"
	printf "AUTHOR :\n"
	printf " Vikry Yuansah\n\n"
	printf "LINK :\n"
	printf " https://github.com/kazuyamarino/nsy/blob/master/docs/OVERVIEW.md\n\n"

	printf "COMMANDS :\n"
	printf " --install\t\t Install or update NSY CLI\n"
	printf " --hello\t\t Show welcome message\n"
	printf " --help\t\t\t Show help\n"
	printf " --version\t\t Show NSY CLI version\n"
	printf " --setup\t\t Setting up NSY for ready to use\n"
	printf " serve\t\t\t Start the PHP built-in dev server (default: 127.0.0.1:8000)\n"
	printf " dump:autoload\t\t Run 'composer dump-autoload -o'\n"
	printf " dump:mysql\t\t Dump a MySQL database\n"
