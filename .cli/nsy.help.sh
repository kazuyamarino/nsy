	printf " migration-name\t\t migration class name\n"
	printf " route-name\t\t route file name\n"
	printf " view-name\t\t view file name\n"
	printf " middleware-name\t middleware class name\n"
	printf " port\t\t\t dev server port for 'serve' (default: 8000)\n"
